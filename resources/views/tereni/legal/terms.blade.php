<h2>2. Šta je servis</h2>
<p>Tereni Medijane je javna mapa sportskih terena i alat za prijavu njihovog stanja (oštećenja, nebezbedno stanje, održavanje). Servis služi za obaveštavanje i praćenje; <strong>ne zamenjuje hitne službe</strong> (112, 192, 194) i ne garantuje da će prijava biti rešena u određenom roku. Informacije o terenima (dimenzije, podloga, pristup) su informativne i mogu biti zastarele.</p>

<h2>3. Prijava problema</h2>
<ul>
    <li>Prijavljujete samo stvarno stanje terena koje ste sami videli, uz svoju fotografiju. Lažne, uvredljive i višestruke prijave nisu dozvoljene.</li>
    <li>Ne fotografišite ljude (posebno decu), registarske tablice niti unosite tuđe lične podatke u opis.</li>
    <li>Prijava se objavljuje tek nakon moderacije. Zadržavamo pravo da prijavu ne objavimo, izmenimo (npr. zamaglimo lica) ili uklonimo bez obrazloženja ako krši ove uslove ili zakon.</li>
    <li>Status prijave (Prijavljeno → Potvrđeno → U planu radova → Rešeno ili Odbijeno uz obrazloženje) menjaju ovlašćena lica; svaka promena se javno beleži sa datumom.</li>
</ul>

<h2>4. Sadržaj koji šaljete</h2>
<p>Zadržavate autorska prava na fotografiju i tekst koje pošaljete, ali nam slanjem dajete neekskluzivnu, neograničenu u vremenu i teritorijalno, besplatnu dozvolu da ih objavimo i prikazujemo na servisu radi javnog praćenja stanja terena. Garantujete da ste vi autor fotografije, da je snimljena na javnom mestu i da njenim objavljivanjem ne kršite tuđa prava. Dozvolu možete opozvati zahtevom za uklanjanje (videti Politiku privatnosti).</p>

<h2>5. Podaci o ličnosti</h2>
<p>Obrada ličnih podataka opisana je u <a href="{{ route('tereni.privacy') }}">Politici privatnosti</a>. Vaše ime i kontakt se ne objavljuju.</p>

<h2>6. Sadržaj servisa</h2>
<p>Dizajn, kod, naziv i znak servisa, kao i fotografije terena koje je obezbedio pružalac, zaštićeni su autorskim pravom. Ne smete ih kopirati niti komercijalno koristiti bez saglasnosti. Pregled i deljenje linkova ka stranicama terena je slobodno. Mapa koristi podatke OpenStreetMap-a (© OpenStreetMap contributors).</p>

<h2>7. Zabranjena upotreba</h2>
<ul>
    <li>automatizovano slanje prijava i preuzimanje u obimu koji ugrožava rad servisa;</li>
    <li>zaobilaženje ograničenja i zaštite, pokušaj neovlašćenog pristupa;</li>
    <li>zloupotreba oznake „prijavi sadržaj“ i lažno predstavljanje.</li>
</ul>

<h2>8. Ograničenje odgovornosti</h2>
<p>Servis se pruža „takav kakav jeste“. Ulažemo razumnu pažnju da podaci budu tačni, ali ne garantujemo tačnost prijava korisnika, dostupnost servisa niti stanje bilo kog terena. Pre korišćenja terena sami procenite njegovu bezbednost. U meri dozvoljenoj zakonom ne odgovaramo za štetu nastalu korišćenjem terena, servisa ili oslanjanjem na objavljene informacije; odgovornost koja se po zakonu ne može isključiti ostaje neizmenjena. Za sadržaj prijava odgovara njihov autor.</p>

<h2>9. Izmene i merodavno pravo</h2>
<p>Uslove možemo izmeniti; važeća verzija je ova stranica, sa datumom poslednje izmene. Primenjuje se pravo Republike Srbije, a za sporove je nadležan stvarno nadležan sud u Nišu, osim ako imperativni propisi predviđaju drugačije.</p>
