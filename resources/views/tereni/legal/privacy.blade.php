<h2>2. Koje podatke obrađujemo</h2>

<h3>Prijava problema na terenu</h3>
<ul>
    <li><strong>Obavezno:</strong> kategorija problema i fotografija terena.</li>
    <li><strong>Opciono:</strong> opis, ime i kontakt (imejl ili telefon) za obaveštenje o statusu prijave.</li>
    <li><strong>Automatski:</strong> IP adresa sa koje je prijava poslata, i vreme prijave.</li>
</ul>
<p><strong>Svrha:</strong> da se problem evidentira, prosledi zaduženom licu i javno prati do rešavanja; da vas obavestimo o promeni statusa (ako ste ostavili kontakt); da sprečimo zloupotrebe i lažne prijave (IP adresa, ograničenje broja prijava).</p>
<p><strong>Pravni osnov:</strong> legitimni interes (održavanje terena i transparentno praćenje prijava, zaštita servisa od zloupotrebe), a za kontakt radi obaveštavanja — vaša saglasnost, koju dajete dobrovoljnim unosom kontakta.</p>

<h3>Šta je javno, a šta nije</h3>
<ul>
    <li><strong>Javno (nakon moderacije):</strong> fotografija, kategorija, opis, datum prijave i istorija statusa sa napomenama.</li>
    <li><strong>Nikada javno:</strong> vaše ime, kontakt i IP adresa. Vide ih samo moderatori i zaduženo lice za dati teren.</li>
</ul>
<blockquote><p>Molimo vas da ne fotografišete ljude (posebno decu) i registarske tablice i da u opis ne upisujete lične podatke. Ako se ipak nađu na fotografiji ili u opisu, moderator ih uklanja ili ne objavljuje prijavu; na zahtev ćemo to učiniti odmah.</p></blockquote>

<h3>Podaci zaduženih lica</h3>
<p>Za svaki objekat vodimo kontakt zaduženog lica (ime, funkcija, telefon, imejl) kome se šalje obaveštenje o novoj prijavi. Pravni osnov je legitimni interes i obaveze povezane sa njihovim zaduženjem; podaci se ne objavljuju.</p>

<h3>Tehnički podaci i kolačići</h3>
<p>Server beleži IP adresu, vreme i tražene adrese radi rada i bezbednosti sajta (čuvaju se najviše 30 dana). Sajt koristi samo tehnički neophodne kolačiće (sesija, zaštita formi); ne koristimo analitiku ni oglašavanje.</p>

<h2>3. Servisi trećih strana</h2>
<ul>
    <li><strong>Google Fonts</strong> — fontovi se učitavaju sa Google servera, pa Google vidi vašu IP adresu.</li>
    <li><strong>OpenStreetMap</strong> (mapa) i <strong>unpkg</strong> (biblioteka Leaflet) — pri otvaranju mape vaš pregledač kontaktira ove servere, koji vide vašu IP adresu.</li>
    <li><strong>Imejl i SMS obaveštenja</strong> — šalju se preko provajdera koji podatke obrađuje samo po našem nalogu.</li>
    <li><strong>Hosting provajder</strong> — obrađivač serverskih zapisa i skladištenja.</li>
</ul>
<p>Neki provajderi imaju servere van Srbije; prenos se vrši uz mere zaštite predviđene zakonom. Podatke ne prodajemo niti ih koristimo za marketing.</p>

<h2>4. Rokovi čuvanja</h2>
<ul>
    <li>Ime, kontakt i IP adresa prijavioca: do 12 meseci nakon zatvaranja prijave, nakon čega se brišu ili anonimizuju.</li>
    <li>Fotografija i opis objavljenih prijava: dok je prijava javno relevantna za praćenje stanja terena; skidamo ih na zahtev ako sadrže podatke o ličnosti.</li>
    <li>Neobjavljene (odbijene u moderaciji) prijave: do 6 meseci.</li>
    <li>Serverski zapisi: najviše 30 dana.</li>
</ul>

<h2>5. Vaša prava</h2>
<p>Imate pravo na informaciju o obradi, pristup i kopiju podataka, ispravku, brisanje, ograničenje obrade, prenosivost, prigovor, kao i na opoziv saglasnosti u svakom trenutku (opoziv ne utiče na obradu pre opoziva). Zahtev šaljite imejlom; odgovaramo u roku od 30 dana (uz mogućnost produženja po zakonu). Ako vam je objavljena fotografija ili opis koji sadrži vaše podatke, navedite link prijave i uklonićemo ih.</p>
<p>Ako smatrate da se podaci obrađuju protivno zakonu, možete podneti pritužbu Povereniku za informacije od javnog značaja i zaštitu podataka o ličnosti (<a href="https://www.poverenik.rs" target="_blank" rel="noopener">www.poverenik.rs</a>).</p>

<h2>6. Deca</h2>
<p>Servis nije namenjen deci mlađoj od 15 godina da samostalno ostavljaju lične podatke. Maloletnici ne treba da unose ime i kontakt bez znanja roditelja. Fotografije na kojima su prepoznatljiva deca ne objavljujemo.</p>

<h2>7. Bezbednost i izmene</h2>
<p>Koristimo šifrovanu vezu (HTTPS), pristup administraciji po ulozi, ograničenje broja prijava i moderaciju pre objave. Politiku možemo menjati; važeća verzija je ova stranica, sa datumom poslednje izmene.</p>
